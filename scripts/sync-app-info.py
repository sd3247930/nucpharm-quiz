"""从唯一版本源 manifest.json 生成 UI 可读的构建信息。"""
import json
import re
from pathlib import Path
root = Path(__file__).resolve().parents[1]
source = re.sub(r'/\*[\s\S]*?\*/', '', (root / 'manifest.json').read_text(encoding='utf-8'))
manifest = json.loads(source)
info = {'version': manifest['versionName'], 'versionCode': manifest['versionCode'], 'appid': manifest['appid']}
(root / 'core/app-info.js').write_text('// Generated by scripts/sync-app-info.py from manifest.json.\nexport default ' + json.dumps(info, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
(root / 'static/app-version.json').write_text(json.dumps(info, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
print('App info synchronized from manifest.json')
