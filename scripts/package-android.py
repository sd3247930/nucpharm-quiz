"""Build a signed APK from compiled uni-app resources and a verified native runtime.

Native code, manifest and icons come from the pinned runtime APK. This is a
resource build, not a replacement for HBuilderX when native configuration changes.
Passwords are accepted only through environment variables and never printed.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import tempfile
from zipfile import ZipFile


def run(command):
    result = subprocess.run([str(arg) for arg in command], capture_output=True, text=True, encoding='utf-8', errors='replace')
    if result.returncode:
        # Avoid leaking command arguments, signer errors or private machine paths.
        raise RuntimeError(f'{Path(command[0]).name} failed (exit {result.returncode})')
    return result.stdout


def build(args):
    root = Path(__file__).resolve().parents[1]
    config = json.loads((root / 'android-runtime.json').read_text(encoding='utf-8'))
    runtime = Path(args.runtime).resolve()
    if hashlib.sha256(runtime.read_bytes()).hexdigest() != config['sha256']:
        raise RuntimeError('Runtime SHA-256 does not match the pinned configuration')
    compiled = Path(args.resources).resolve()
    for name in ('app-service.js', 'app-config-service.js', '__uniappview.html', 'manifest.json'):
        if not (compiled / name).is_file():
            raise RuntimeError(f'Missing compiled App resource: {name}')
    manifest = json.loads((compiled / 'manifest.json').read_text(encoding='utf-8'))
    prefix = f"assets/apps/{manifest['id']}/www/"
    if manifest['id'] != config['appid']:
        raise RuntimeError('App id changed: regenerate the native runtime in HBuilderX')
    sdk = Path(args.build_tools).resolve()
    suffix = '.exe' if os.name == 'nt' else ''
    java = os.environ.get('JAVA_EXE', 'java')
    signer = [java, '-jar', sdk / 'lib/apksigner.jar']
    cert = lambda apk: re.search(r'certificate SHA-256 digest: ([0-9a-f]+)', run(signer + ['verify', '--print-certs', apk])).group(1)
    expected_cert = cert(runtime)
    with tempfile.TemporaryDirectory(prefix='nucpharm-apk-') as workspace:
        work = Path(workspace)
        unsigned, aligned = work / 'unsigned.apk', work / 'aligned.apk'
        with ZipFile(runtime) as original:
            original_manifest = json.loads(original.read(prefix + 'manifest.json'))
            if original_manifest['version'] != manifest['version']:
                raise RuntimeError('Native version changed: regenerate and pin a matching HBuilderX runtime')
            original_manifest['plus']['splashscreen'].update(manifest.get('plus', {}).get('splashscreen', {}))
            updates = {prefix + p.relative_to(compiled).as_posix(): p.read_bytes() for p in compiled.rglob('*') if p.is_file()}
            updates[prefix + 'manifest.json'] = json.dumps(original_manifest, ensure_ascii=False, separators=(',', ':')).encode('utf-8')
            with ZipFile(unsigned, 'w') as destination:
                for entry in original.infolist():
                    if re.fullmatch(r'META-INF/(?:[^/]+\.(?:SF|RSA|DSA|EC)|MANIFEST\.MF)', entry.filename, re.I):
                        continue
                    # Retain native-runtime helpers not generated by uni CLI.
                    destination.writestr(entry, updates.pop(entry.filename, original.read(entry.filename)))
                for name, data in updates.items():
                    destination.writestr(name, data)
        run([sdk / ('zipalign' + suffix), '-P', '16', '-f', '4', unsigned, aligned])
        keystore = os.environ.get('ANDROID_KEYSTORE')
        release = bool(keystore)
        if not release:
            if args.require_release:
                raise RuntimeError('Release signing secrets are required; refusing a debug-signed public release')
            debug = root / 'private/android-signing/local-debug.keystore'
            debug.parent.mkdir(parents=True, exist_ok=True)
            if not debug.exists():
                run(['keytool', '-genkeypair', '-keystore', debug, '-storepass', 'android', '-keypass', 'android', '-alias', 'androiddebugkey', '-dname', 'CN=Android Debug,O=Android,C=US', '-keyalg', 'RSA', '-keysize', '2048', '-validity', '10000'])
            keystore = str(debug)
            os.environ.update({'ANDROID_STORE_PASSWORD': 'android', 'ANDROID_KEY_PASSWORD': 'android', 'ANDROID_KEY_ALIAS': 'androiddebugkey'})
        for name in ('ANDROID_STORE_PASSWORD', 'ANDROID_KEY_PASSWORD', 'ANDROID_KEY_ALIAS'):
            if not os.environ.get(name):
                raise RuntimeError(f'Missing signing environment variable: {name}')
        output = Path(args.output).resolve()
        output.parent.mkdir(parents=True, exist_ok=True)
        run(signer + ['sign', '--ks', keystore, '--ks-key-alias', os.environ['ANDROID_KEY_ALIAS'], '--ks-pass', 'env:ANDROID_STORE_PASSWORD', '--key-pass', 'env:ANDROID_KEY_PASSWORD', '--v1-signing-enabled', 'true', '--v2-signing-enabled', 'true', '--v3-signing-enabled', 'true', '--v4-signing-enabled', 'false', '--out', output, aligned])
        if release and cert(output) != expected_cert:
            raise RuntimeError('Signing identity differs from runtime; this cannot update existing installs')
        run([sdk / ('zipalign' + suffix), '-c', '-P', '16', '4', output])
        with ZipFile(runtime) as before, ZipFile(output) as after:
            native = [n for n in before.namelist() if not n.startswith(prefix) and not n.startswith('META-INF/')]
            if any(before.read(n) != after.read(n) for n in native):
                raise RuntimeError('Native runtime unexpectedly changed')
            for p in compiled.rglob('*'):
                if p.is_file() and p.name != 'manifest.json':
                    assert after.read(prefix + p.relative_to(compiled).as_posix()) == p.read_bytes()
        digest = hashlib.sha256(output.read_bytes()).hexdigest()
        output.with_name(output.name + '.sha256').write_text(f'{digest}  {output.name}\n', encoding='utf-8')
        print(json.dumps({'status': 'PASS', 'file': output.name, 'sha256': digest, 'releaseSigned': release, 'nativeRuntimePreserved': True, 'allCompiledResourcesVerified': True}))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--runtime', required=True)
    parser.add_argument('--resources', default='unpackage/dist/build/app-plus')
    parser.add_argument('--build-tools', required=True)
    parser.add_argument('--output', default='unpackage/releases/NucPharm.apk')
    parser.add_argument('--require-release', action='store_true')
    build(parser.parse_args())
